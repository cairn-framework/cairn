    #[test]
    fn test_contract_pointer_target_matches_written_contract_file() {
        // The delta pointer and the change-directory filename are produced by
        // two different writers; this pins them together.
        let dir = tempfile::tempdir().expect("tempdir");
        let root = dir.path();
        let ext = extraction(vec![candidate("app.payments", "Payments", "payments/")]);
        write_change(root, "c1", &ext, &[]).expect("write_change must succeed");
        let delta = std::fs::read_to_string(root.join("meta/changes/c1/blueprint.delta"))
            .expect("delta must exist");
        let pointer = delta
            .lines()
            .find_map(|line| line.trim().strip_prefix("contract "))
            .expect("delta must declare a contract pointer");
        let file_name = pointer
            .trim_matches('"')
            .rsplit('/')
            .next()
            .expect("basename");
        assert!(
            root.join("meta/changes/c1/contracts")
                .join(file_name)
                .exists(),
            "pointer target `{file_name}` must be the file write_change wrote"
        );
    }

    #[test]
    fn test_write_change_proposal_carries_review_checklist() {
        // The reviewer opens proposal.md, not docs/brownfield.md, so the
        // artefact itself has to disclaim the confidence column and name the
        // curation the map still needs.
        let dir = tempfile::tempdir().expect("tempdir");
        let root = dir.path();
        let ext = extraction(vec![candidate("app.payments", "Payments", "payments/")]);
        write_change(root, "c1", &ext, &[]).expect("write_change must succeed");
        let proposal = std::fs::read_to_string(root.join("meta/changes/c1/proposal.md"))
            .expect("proposal must exist");
        assert!(
            proposal.contains(
                "Confidence is a structural signal, not a claim of architectural correctness"
            ),
            "proposal must disclaim confidence: {proposal}"
        );
        assert!(
            proposal.contains("docs/brownfield.md"),
            "proposal must point at the limits doc: {proposal}"
        );
        for item in [
            "Path ownership",
            "Grouping",
            "Edges",
            "Contracts",
            "Currency",
            "Hierarchy",
        ] {
            assert!(
                proposal.contains(&format!("- [ ] {item}:")),
                "review checklist must cover `{item}`: {proposal}"
            );
        }
        assert!(
            proposal.find("## Candidates").expect("candidates heading")
                < proposal
                    .find("## Review before applying")
                    .expect("review heading"),
            "the checklist follows the candidate list it applies to"
        );
    }

    #[test]
    fn test_blueprint_delta_marks_discovered_edges() {
        let mut api = candidate("app.api", "Api", "api/");
        api.edges.push(DiscoveredEdge {
            target: "app.db".to_owned(),
            description: "imports".to_owned(),
            confidence: 0.8,
        });
        let mut db = candidate("app.db", "Db", "db/");
        db.edges.push(DiscoveredEdge {
            target: "app.api".to_owned(),
            description: "imports".to_owned(),
            confidence: 0.8,
        });
        let delta = blueprint_delta(&extraction(vec![api, db]));
        assert!(delta.contains("## ADDED Edges"));
        assert!(
            delta.contains(r#"app.api -> app.db "imports" @inferred"#),
            "forward discovered edge must carry the provenance marker: {delta:?}"
        );
        assert!(
            delta.contains(r#"app.db -> app.api "imports" @inferred"#),
            "reverse discovered edge must carry the provenance marker: {delta:?}"
        );
    }

