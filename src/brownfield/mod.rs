    fn candidate(id: &str, name: &str, path: &str) -> DiscoveredCandidate {
        DiscoveredCandidate {
            id: id.to_owned(),
            name: name.to_owned(),
            description: "Handles payments".to_owned(),
            path: path.to_owned(),
            tags: Vec::new(),
            confidence: 0.9,
            evidence: Vec::new(),
            edges: Vec::new(),
        }
    }

    fn extraction(candidates: Vec<DiscoveredCandidate>) -> Extraction {
        Extraction {
            candidates,
            schema_version: 1,
        }
    }

