/// Generate a stub contract for a discovered candidate.
#[must_use]
pub fn stub_contract(candidate: &DiscoveredCandidate) -> String {
    format!(
        "---\noperation: added\nnode: {}\n---\n# {}\n\n{}\n",
        candidate.id,
        candidate.name,
        candidate.description.trim_end()
    )
}

/// Contract artefact filename for a candidate id. The change directory writes
/// this name and the blueprint delta points at it, so both derive it here.
fn contract_file_name(id: &str) -> String {
    format!("{}.md", id.replace('.', "_"))
}

/// Blueprint `contract` pointer for a candidate id. Targets the path
/// `parse_artefact_operations` promotes the change's contract file to
/// (`meta/` joined with the artefact's path relative to the change directory).
fn contract_pointer(id: &str) -> String {
    format!("./meta/contracts/{}", contract_file_name(id))
}

/// Appended to every generated brownfield proposal. Discovery is filesystem
/// evidence, so the artefact a reviewer opens has to say what the confidence
/// column does and does not claim, and name the curation this map still needs.
const REVIEW_CHECKLIST: &str = "\n## Review before applying\n\n\
Confidence is a structural signal, not a claim of architectural correctness: it \
scores how many source files a candidate holds, nothing more. Discovery groups \
files by where they sit on disk and cannot see how the system divides \
responsibility. Correct this proposal before you apply it. The scoring rules and \
their limits are described in `docs/brownfield.md`.\n\n\
- [ ] Path ownership: no two candidates claim overlapping or nested paths.\n\
- [ ] Grouping: each candidate is one responsibility, not one directory that \
happens to hold several.\n\
- [ ] Edges: every real dependency is declared, and no declared edge is invented.\n\
- [ ] Contracts: each stub states the interface callers actually rely on.\n\
- [ ] Currency: stale or abandoned planning material is excluded, not mapped as \
live code.\n\
- [ ] Hierarchy: regroup related candidates under appropriate Systems and \
Containers.\n";

/// Write a brownfield change directory with proposal, blueprint delta,
/// and stub contracts.
///
/// # Errors
///
/// Returns `CairnError::WriteOutput` when any file cannot be written.
pub fn write_change(
    root: &std::path::Path,
    change_id: &str,
    extraction: &Extraction,
    templates: &[templates::ContractTemplate],
) -> Result<(), CairnError> {
    let change_dir = root.join("meta/changes").join(change_id);
    create_dir(&change_dir)?;
    create_dir(&change_dir.join("contracts"))?;

    let mut proposal = format!(
        "# Proposal: {change_id}\n\nGenerated by brownfield extraction.\n\n## Candidates\n\n",
    );
    if extraction.candidates.is_empty() {
        proposal.push_str("_No module candidates discovered._\n");
    }
    for candidate in &extraction.candidates {
        let _ = writeln!(
            proposal,
            "- `{}` ({}) at `{}` (confidence {:.2})",
            candidate.id, candidate.name, candidate.path, candidate.confidence
        );
    }
    proposal.push_str(REVIEW_CHECKLIST);
    write_file(&change_dir.join("proposal.md"), &proposal)?;

    let delta = blueprint_delta(extraction);
    write_file(&change_dir.join("blueprint.delta"), &delta)?;

    for candidate in &extraction.candidates {
        let contract = templates::render_stub(candidate, templates);
        let file_name = contract_file_name(&candidate.id);
        write_file(&change_dir.join("contracts").join(file_name), &contract)?;
    }

    suggest::write_suggested_edges(&change_dir, extraction, "phase-9-brownfield", "propose")?;

    Ok(())
}

/// Render a blueprint delta from an extraction result.
#[must_use]
pub fn blueprint_delta(extraction: &Extraction) -> String {
    let mut out = String::new();
    if !extraction.candidates.is_empty() {
        out.push_str("## ADDED Nodes\n");
        for candidate in &extraction.candidates {
            let path = format!("./{}", candidate.path);
            let _ = writeln!(
                out,
                "{} {} {:?} id {:?} {{",
                node_kind_from_path(&candidate.path),
                bareword(&candidate.name),
                candidate.description,
                candidate.id,
            );
            let _ = writeln!(out, "    path {path:?}");
            let _ = writeln!(out, "    contract {:?}", contract_pointer(&candidate.id));
            out.push_str("}\n\n");
        }
    }
    let mut edges = String::new();
    for candidate in &extraction.candidates {
        for edge in &candidate.edges {
            let _ = writeln!(
                edges,
                "{} -> {} {:?} @{}",
                candidate.id,
                edge.target,
                edge.description,
                EdgeProvenance::MARKER
            );
        }
    }
    if !edges.is_empty() {
        out.push_str("## ADDED Edges\n");
        out.push_str(&edges);
        out.push('\n');
    }
    out
}

fn node_kind_from_path(path: &str) -> &'static str {
    let segments: Vec<&str> = path.split(['/', '\\']).collect();
    if segments.iter().any(|s| *s == "api" || *s == "service") {
        "Container"
    } else {
        "Module"
    }
}

/// Convert a discovered display name into a single bareword token. The blueprint
/// grammar's node-name slot is a bareword, not a string, so a multi-word name
/// like "api gateway" must collapse to "`ApiGateway`" to parse.
fn bareword(name: &str) -> String {
    let mut out = String::new();
    for word in name.split(|c: char| !c.is_alphanumeric()) {
        let mut chars = word.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.push_str(chars.as_str());
        }
    }
    if out.is_empty() {
        "Module".to_owned()
    } else {
        out
    }
}

fn create_dir(path: &std::path::Path) -> Result<(), CairnError> {
    std::fs::create_dir_all(path).map_err(|e| CairnError::WriteOutput {
        path: path.to_string_lossy().to_string(),
        detail: e.to_string(),
    })
}

fn write_file(path: &std::path::Path, content: &str) -> Result<(), CairnError> {
    std::fs::write(path, content).map_err(|e| CairnError::WriteOutput {
        path: path.to_string_lossy().to_string(),
        detail: e.to_string(),
    })
}

